	// 构造方法：初始化时优先读取外部文件，失败则用默认数据
	public Lang_zh_CN() {
		super();
		Object[][] fileData = loadConfigFromFile();
		// 判断文件读取结果：非空则用文件数据，空则用默认数据
		this.data = (fileData != null && fileData.length > 0) ? fileData : DEFAULT_DATA;
	}

	/**
	 * 从外部文件读取配置，解析为键值对数组
	 * @return 解析后的数组（失败则返回null）
	 */
	private Object[][] loadConfigFromFile() {
		List<Object[]> keyValueList = new ArrayList<>();
		File configFile = new File(CONFIG_PATH);

		// 1. 检查文件是否存在
		if (!configFile.exists()) {
			LOGGER.log(Level.WARNING, "配置文件不存在：{0}（路径：{1}），将使用默认数据",
					new Object[]{CONFIG_PATH, configFile.getAbsolutePath()});
			return null;
		}

		// 2. 读取并解析文件
		try (InputStreamReader isr = new InputStreamReader(new FileInputStream(configFile), "UTF-8");
			 BufferedReader br = new BufferedReader(isr)) {

			String line;
			int lineNum = 0;
			while ((line = br.readLine()) != null) {
				lineNum++;
				String trimmedLine = line.trim();
				// 跳过空行和注释（#开头）
				if (trimmedLine.isEmpty() || trimmedLine.startsWith("#")) {
					continue;
				}
				// 按第一个"="分割（避免值中包含"="）
				String[] keyValue = trimmedLine.split("=", 2);
				if (keyValue.length != 2) {
					LOGGER.log(Level.WARNING, "配置文件第{0}行格式错误（需为「键=值」）：{1}，该行将忽略",
							new Object[]{lineNum, trimmedLine});
					continue;
				}
				// 提取键值对（去空格）
				String key = keyValue[0].trim();
				String value = keyValue[1].trim();
				keyValueList.add(new Object[]{key, value});
			}

			// 3. 转换为二维数组并返回
			Object[][] result = new Object[keyValueList.size()][2];
			for (int i = 0; i < keyValueList.size(); i++) {
				result[i] = keyValueList.get(i);
			}
			LOGGER.log(Level.INFO, "成功加载配置文件：{0}，共{1}个键值对",
					new Object[]{CONFIG_PATH, result.length});
			return result;

		} catch (IOException e) {
			LOGGER.log(Level.SEVERE, "读取配置文件时发生IO错误：" + CONFIG_PATH, e);
			LOGGER.log(Level.WARNING, "将使用默认硬编码数据");
			return null;
		} catch (Exception e) {
			LOGGER.log(Level.SEVERE, "解析配置文件时发生未知错误：" + CONFIG_PATH, e);
			LOGGER.log(Level.WARNING, "将使用默认硬编码数据");
			return null;
		}
	}

	/**
	 * 重写ListResourceBundle核心方法，返回最终使用的键值对
	 */
	@Override
	protected Object[][] getContents() {
		return this.data;
	}

	// 保留原有的setter和getter，保持兼容性
	public void setData(Object data[][]) {
		this.data = data;
	}

	public Object[][] getData() {
		return data;
	}
